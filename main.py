@dp.message()
async def send_broadcast(message: types.Message):
    if message.from_user.id != ADMIN_ID:
        return

    for user_id in users:
        try:
            await bot.send_message(
                user_id,
                message.text
            )
        except Exception:
            pass

    await message.answer(
        f"✅ Сообщение отправлено {len(users)} пользователям."
    )

